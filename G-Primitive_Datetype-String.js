

// Example 1 (String using Characters)

let firstName = "Vignesh";

let lastName  = "Baskaran";

let Initial   = "B";

console.log("FullName===>",firstName +" "+ lastName)

console.log("Initial===>", typeof Initial)


// Example 2 (String using Numbers)

let firstNumber = "100";

let lastNumber  = "200";

console.log("FullName===>",firstNumber+lastNumber)

// Since the numbers are enclosed in quotes, JavaScript treats them as strings rather than numbers.


// Example 3 (String using Boolean,Null, Undefined)

let IsAvailable = "true";

let x  = "200";

let y  = "undefined";

let z  = "null";

console.log("IsAvailable===>",typeof IsAvailable)

console.log("x===>",typeof x)

console.log("y===>",typeof y)

console.log("z===>",typeof z)


// Since the Boolean, Null, Undefined are enclosed in quotes, JavaScript treats them as strings rather than numbers.


