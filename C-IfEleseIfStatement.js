// "Excellent" if marks ≥ 90
// "Good" if marks ≥ 70
// "Average" if marks ≥ 40
// "Fail" otherwise

// Example 1 

let marks = 30;

if(marks >= 90) {

    console.log("Excellent Student")

} else if (marks >= 70){

    console.log("Good Student")

} else if (marks >= 40){

    console.log("Average Student")

} else {

    console.log("Fail")
}